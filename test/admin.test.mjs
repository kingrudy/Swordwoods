// Beheer: sleutel nodig, dempen werkt in de chat, uit het spel zetten, blokkeren, nieuw wachtwoord, aankondiging; spelers kunnen hun wachtwoord wijzigen.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import { ROOT, tmpData } from './helpers.mjs';
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const PORT = 8133, B = 'http://localhost:' + PORT, DATA = tmpData('admin'), sleep = ms => new Promise(r => setTimeout(r, ms));
fs.rmSync(DATA, { recursive: true, force: true });
const srv = spawn('node', ['server.js'], { cwd: ROOT, env: { ...process.env, PORT, EXTRA_PORTS: '', DATA_DIR: DATA, ADMIN_KEY: 'geheim-beheer-123', FIRST_WAVE_DELAY: 999 }, stdio: ['ignore', 'pipe', 'inherit'] });
await new Promise(r => srv.stdout.on('data', d => String(d).includes('luistert') && r()));
const BUILD = (await (await fetch(B + '/api/health')).json()).build;
const post = async (p, body, key) => { const r = await fetch(B + p, { method: 'POST', headers: key ? { 'X-Admin-Key': key } : {}, body: JSON.stringify(body) }); return { status: r.status, j: await r.json() }; };
const admin = (act, body) => post('/api/admin/' + act, body, 'geheim-beheer-123');
const reg = async n => (await post('/api/register', { username: n, password: 'abcdef1' })).j.token;
async function bot(name, token) {
  const b = { msgs: [], ws: new WebSocket(B.replace('http', 'ws') + '/ws') };
  b.send = m => b.ws.send(JSON.stringify(m));
  b.ws.onopen = () => b.send({ t: 'auth', build: BUILD, token });
  b.ws.onmessage = e => { const m = JSON.parse(e.data); if (m.t === 'authed') b.send({ t: 'join', id: 1 }); if (m.t !== 's') b.msgs.push(m); };
  b.ws.onclose = () => b.closed = true;
  for (let i = 0; i < 40 && !b.msgs.some(m => m.t === 'joined'); i++) await sleep(100);
  return b;
}
const tA = await reg('Lastpak'), tB = await reg('Luisteraar');
const A = await bot('Lastpak', tA), L = await bot('Luisteraar', tB);
ok((await (await fetch(B + '/admin')).text()).includes('Swordwoods · beheer'), 'beheerpagina bereikbaar');
ok((await fetch(B + '/api/admin/overview')).status === 401, 'zonder sleutel geen toegang');
ok((await fetch(B + '/api/admin/overview', { headers: { 'X-Admin-Key': 'fout' } })).status === 401, 'verkeerde sleutel geweigerd');
A.send({ t: 'chat', text: 'hallo allemaal' }); await sleep(400);
const ov = await (await fetch(B + '/api/admin/overview', { headers: { 'X-Admin-Key': 'geheim-beheer-123' } })).json();
ok(ov.users.length === 2 && ov.users.every(u => u.online) && ov.chat.some(c => c.text === 'hallo allemaal'), 'overzicht met online spelers en chatlog');
ok((await admin('mute', { user: 'lastpak', minutes: 10, reason: 'schelden' })).j.ok, 'gedempt');
await sleep(900); const before = L.msgs.filter(m => m.t === 'chat').length;
A.send({ t: 'chat', text: 'nog een keer' }); await sleep(400);
ok(L.msgs.filter(m => m.t === 'chat').length === before && A.msgs.some(m => m.t === 'toast' && /gedempt/.test(m.msg)), 'gedempte speler kan niet chatten');
await admin('unmute', { user: 'lastpak' }); await sleep(900); A.send({ t: 'chat', text: 'sorry' }); await sleep(400);
ok(L.msgs.some(m => m.t === 'chat' && m.text === 'sorry'), 'na opheffen weer chatten');
ok((await admin('announce', { text: 'Server herstart zo' })).j.sent === 2 && (await sleep(300), L.msgs.some(m => m.t === 'announce')), 'aankondiging komt aan');
await admin('kick', { user: 'lastpak', reason: 'even afkoelen' }); await sleep(400);
ok(A.closed && A.msgs.some(m => m.t === 'kicked' && /afkoelen/.test(m.reason)), 'uit het spel gezet met reden');
await admin('ban', { user: 'lastpak', reason: 'herhaald' });
ok(/geblokkeerd/.test((await post('/api/login', { username: 'Lastpak', password: 'abcdef1' })).j.err || ''), 'geblokkeerde speler kan niet inloggen');
const A2 = await bot('Lastpak', tA); ok(!A2.msgs.some(m => m.t === 'joined'), 'oude sessie werkt ook niet meer');
await admin('unban', { user: 'lastpak' });
const r = await admin('resetpw', { user: 'luisteraar' }); await sleep(300);
ok(r.j.password && L.closed, 'nieuw wachtwoord gemaakt, speler uitgelogd');
const t2 = (await post('/api/login', { username: 'Luisteraar', password: r.j.password })).j.token;
ok(!!t2, 'inloggen met het nieuwe wachtwoord');
ok((await post('/api/password', { token: t2, old: 'fout', pw: 'nieuw123' })).status === 400, 'wachtwoord wijzigen met verkeerd oud wachtwoord geweigerd');
ok((await post('/api/password', { token: t2, old: r.j.password, pw: 'nieuw123' })).j.ok && (await post('/api/login', { username: 'Luisteraar', password: 'nieuw123' })).j.token, 'speler wijzigt zelf zijn wachtwoord');
const bk = await admin('backup-now', {}); ok(bk.j.ok && fs.readdirSync(DATA + '/backups').length >= 1, 'back-up op verzoek');
srv.kill(); console.log(fails ? fails + ' MISLUKT' : 'ALLES GESLAAGD'); process.exit(fails ? 1 : 0);
